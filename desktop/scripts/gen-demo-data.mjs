#!/usr/bin/env node
/**
 * Builds the demo-mode dataset from real captured `bob --json` envelopes.
 *
 * Usage: node scripts/gen-demo-data.mjs [sampleDir] [workspaceDir]
 * Output: src/renderer/src/state/demoData.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(here, '..')
const sampleDir = resolve(process.argv[2] ?? '/tmp/bob-json')
const workspaceDir = resolve(process.argv[3] ?? '/tmp/bob-ws-go')

/** featureId -> sample file basename */
const MAP = {
  version: 'version',
  explain: 'explain',
  learn: 'learn',
  'recipe-list': 'recipe-list',
  'recipe-show': 'recipe-show-ts',
  init: 'init-preview',
  'init-write': 'init-ts-write',
  new: 'new-preview',
  'new-write': 'new-go-write',
  plan: 'go-plan-conflict',
  'plan-clean': 'ts-plan',
  apply: 'ts-apply',
  'apply-refused': 'go-apply-refused',
  'apply-digest-mismatch': 'go-apply-digest-mismatch',
  check: 'go-check-conflict',
  'check-clean': 'ts-check',
  upgrade: 'go-upgrade-dry',
  remove: 'go-remove-dry',
  path: 'go-path-conflict',
  'path-batch': 'ts-path-batch',
  context: 'context-full',
  'context-workspace': 'go-context',
  'playbook-list': 'go-playbook-list',
  'playbook-show': 'ts-playbook-show',
  'playbook-plan': 'go-playbook-plan',
  doctor: 'doctor',
  inspect: 'go-inspect',
  'config-show': 'config-show',
  'config-init': 'config-init-preview',
  stats: 'ts-stats'
}

function readSample(name) {
  const file = join(sampleDir, `${name}.json`)
  if (!existsSync(file)) return null
  const text = readFileSync(file, 'utf8')
  try {
    JSON.parse(text)
  } catch {
    return null
  }
  return text
}

/**
 * Captures come from a real machine, so they carry private absolute paths.
 * The published repository must not contain them, so every path is rewritten
 * to a neutral root before the data is embedded.
 */
const SCRUBS = [
  [/\/Users\/[A-Za-z0-9._-]+/g, '/home/dev'],
  [/\/private\/tmp\/bob-ws-go/g, '/workspaces/demo-go'],
  [/\/private\/tmp\/bob-ws-ts/g, '/workspaces/demo-ts'],
  [/\/private\/tmp/g, '/workspaces'],
  [/\/tmp\/bob-ws-go/g, '/workspaces/demo-go'],
  [/\/tmp\/bob-ws-ts/g, '/workspaces/demo-ts']
]

function scrub(text) {
  let out = text
  for (const [pattern, replacement] of SCRUBS) out = out.replace(pattern, replacement)
  return out
}

const samples = {}
const missing = []
for (const [featureId, name] of Object.entries(MAP)) {
  const text = readSample(name)
  if (text === null) {
    missing.push(`${featureId} (${name})`)
    continue
  }
  samples[featureId] = JSON.parse(scrub(text))
}

const manifestPath = join(workspaceDir, 'bob.yaml')
const lockPath = join(workspaceDir, 'bob.lock')
const manifest = existsSync(manifestPath) ? readFileSync(manifestPath, 'utf8') : ''
const lock = existsSync(lockPath) ? readFileSync(lockPath, 'utf8') : ''

const output = `/* Generated by scripts/gen-demo-data.mjs from real \`bob --json\` output. Do not edit by hand. */

export const DEMO_WORKSPACE = ${JSON.stringify(scrub(workspaceDir))}

export const DEMO_MANIFEST = ${JSON.stringify(scrub(manifest))}

export const DEMO_LOCK = ${JSON.stringify(scrub(lock))}

/** featureId -> captured envelope, replayed verbatim in demo mode. */
export const DEMO_SAMPLES: Record<string, unknown> = ${JSON.stringify(samples, null, 2)}
`

const target = join(projectRoot, 'src/renderer/src/state/demoData.ts')
writeFileSync(target, output, 'utf8')
console.log(`wrote ${target}`)
console.log(`features: ${Object.keys(samples).length}`)
if (missing.length > 0) console.log(`missing samples: ${missing.join(', ')}`)
